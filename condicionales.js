// Definimos una constante con la edad
const edad = 18;

// Estructura condicional if / else
if (edad >= 18) {
    // Si la condición (edad mayor o igual a 18) es VERDADERA:
    console.log("¡Sos mayor de edad! Podes pasar.");
} else {
    // Si la condición es FALSA:
    console.log("Sos menor de edad. Acceso restringido.");
}